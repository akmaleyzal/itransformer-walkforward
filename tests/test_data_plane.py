"""Data-plane tests: the runnable half of the anti-leakage checklist.

Reads ``data/raw/BTCUSDT_1h.parquet``, ``data/raw/BTCUSDT_1h_report.json`` and
``data/raw/BTCUSDT_1h_gaps.csv``. Writes nothing.

A checklist that lives only in prose is a checklist nobody runs. Every test here
corresponds to one leakage check, and the fatal ones say so.
"""

